// 获取单位下的用户
export function getUsersByOrg(orgId: string): User[] {
  return users.filter((u) => u.orgId === orgId);
}

// 获取单位及子单位的用户
export function getUsersByOrgTree(orgId: string, descendantIds: string[]): User[] {
  const idSet = new Set([orgId, ...descendantIds]);
  return users.filter((u) => idSet.has(u.orgId));
}
